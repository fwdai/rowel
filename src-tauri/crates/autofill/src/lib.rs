/// ES256, the one algorithm the vault's keys are.
const ES256: i64 = -7;

uniffi::setup_scaffolding!();

/// Why the vault cannot be read. Each case is one thing the extension says.
#[derive(Debug, thiserror::Error, uniffi::Error)]
pub enum AutofillError {
    /// No vault in the container: Rowel was never set up on this device, or
    /// its data is still in the app's own sandbox (an App Group the build was
    /// not entitled to).
    #[error("there is no vault on this device")]
    NoVault,
    /// Nothing here is unlockable without the master password: Face ID unlock
    /// is off, or the active workspace has no key sealed under the app key.
    #[error("unlock with Face ID is not turned on for this vault")]
    Locked,
    /// The key read from the keychain does not open the vault.
    #[error("the Face ID key does not open this vault")]
    WrongKey,
    /// A master-password change was interrupted. The app rolls the vault back
    /// at its next unlock; until then the database and the sealed payloads
    /// may be on different keys, and nothing here writes but a passkey.
    #[error("Rowel is finishing a password change")]
    Recovering,
    /// Nothing to fill under that record for that site: the login is gone,
    /// another workspace's, moved to another site, or has no password. For a
    /// passkey sign-in, no passkey for the site that the request admits (and
    /// the record names, when it names one): iOS's `credentialIdentityNotFound`.
    #[error("no such login")]
    NotFound,
    /// A passkey sign-in with several accounts to be and none picked: the
    /// sheet lists them rather than asking with no record.
    #[error("no account was picked")]
    Denied,
    /// The registration's exclude list names a passkey this vault holds: the
    /// account already has one here, and a second is not made.
    #[error("Rowel already has a passkey for this account")]
    Excluded,
    /// The relying party takes no ES256 key, the one kind the vault makes.
    #[error("this site does not accept the kind of passkey Rowel makes")]
    Unsupported,
    #[error("{message}")]
    Io { message: String },
}

impl From<StoreError> for AutofillError {
    fn from(e: StoreError) -> Self {
        match e {
            StoreError::WrongKey => Self::WrongKey,
            e => Self::Io {
                message: e.to_string(),
            },
        }
    }
}

impl From<rowel_core::error::Error> for AutofillError {
    fn from(e: rowel_core::error::Error) -> Self {
        Self::Io {
            message: e.to_string(),
        }
    }
}

/// The active vault's place, and the keychain item its key is in. Read
/// without the key: what Swift needs to know before it asks for Face ID.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct VaultLocation {
    /// The data dir: `<container>/app.rowel.mobile`, and its `dev` subdir in a
    /// debug build, as the app lays it out (`layout::app_group_root`).
    pub root: String,
    /// The active workspace, as the registry names it.
    pub workspace: String,
    /// The generic-password item holding the app key, in the App Group's
    /// keychain access group: the account is the one for the gate the app
    /// enrolled behind.
    pub keychain_service: String,
    pub keychain_account: String,
}

/// A login offered for the site, with nothing secret in it: a row's name, the
/// name it signs in with and its site. `record` is the credential identity's
/// `"<workspace id>/<entry id>"`, as the app publishes it to iOS.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct Credential {
    pub record: String,
    pub title: String,
    pub user: String,
    pub host: String,
}

/// What a chosen login fills.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct Password {
    pub user: String,
    pub password: String,
}

/// A passkey the vault holds for a relying party, named the way the site named
/// it at registration; nothing that signs. `record` is the login it is on, in
/// the form the app publishes it to iOS as an `ASPasskeyCredentialIdentity`'s
/// `recordIdentifier` — one login can carry several passkeys, so the
/// credential id is what names the passkey itself.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct PasskeyAccount {
    pub record: String,
    pub credential_id: Vec<u8>,
    pub user_name: String,
    pub user_display_name: String,
    /// RFC 3339, when the vault has it: what tells two same-named passkeys
    /// apart.
    pub created_at: Option<String>,
}

/// A registration, as iOS hands it over (`ASPasskeyCredentialRequest`).
#[derive(Debug, Clone, uniffi::Record)]
pub struct PasskeyRegistration {
    pub rp_id: String,
    pub rp_name: Option<String>,
    pub user_name: String,
    pub user_display_name: Option<String>,
    pub user_handle: Vec<u8>,
    /// The SHA-256 of the `clientDataJSON` iOS wrote.
    pub client_data_hash: Vec<u8>,
    pub excluded_credential_ids: Vec<Vec<u8>>,
    /// COSE algorithm identifiers the relying party takes; empty is any.
    pub supported_algorithms: Vec<i64>,
}

/// What `ASPasskeyRegistrationCredential` carries back besides what iOS sent.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct RegisteredPasskey {
    pub credential_id: Vec<u8>,
    /// CBOR, "none" attestation.
    pub attestation_object: Vec<u8>,
}

/// A sign-in, as iOS hands it over (`ASPasskeyCredentialRequestParameters` for
/// the list, `ASPasskeyCredentialRequest` for a QuickType identity), and the
/// account the user picked.
#[derive(Debug, Clone, uniffi::Record)]
pub struct PasskeyAssertion {
    pub rp_id: String,
    /// The SHA-256 of the `clientDataJSON` iOS wrote.
    pub client_data_hash: Vec<u8>,
    /// The ids the relying party allows; empty is any of the site's.
    pub allowed_credential_ids: Vec<Vec<u8>>,
    /// The login picked: a [`PasskeyAccount`]'s record, or a QuickType
    /// identity's `recordIdentifier`. With it, name the passkey itself by
    /// narrowing `allowed_credential_ids` to the one picked, since one login
    /// can carry several. With none, the site must leave exactly one account.
    pub record: Option<String>,
}

/// What `ASPasskeyAssertionCredential` carries back besides what iOS sent.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct AssertedPasskey {
    pub credential_id: Vec<u8>,
    pub user_handle: Vec<u8>,
    pub authenticator_data: Vec<u8>,
    /// DER-encoded ECDSA over `authenticator_data || client_data_hash`.
    pub signature: Vec<u8>,
}

/// The App Group the vault and the key are shared through — one spelling for
/// the Swift side as well (`rowel_core::app::APP_GROUP`).
#[uniffi::export]
pub fn app_group() -> String {
    rowel_core::app::APP_GROUP.to_string()
}

/// Where the active vault is in the App Group container at `container`, and
/// which keychain item opens it.
#[uniffi::export]
pub fn vault_location(container: String) -> Result<VaultLocation, AutofillError> {
    let root = layout::app_group_root(Path::new(&container));
    let workspace = Registry::load(&root).active;
    let dir = dir_of(&root, &workspace);
    ready(&dir)?;
    // The marker names the gate the key went in behind, and so the item's
    // account. No marker, no key.
    let marker =
        fs::read_to_string(root.join(BIOMETRIC_FILE)).map_err(|_| AutofillError::Locked)?;
    let keychain_account = match GateMode::from_marker(&marker) {
        GateMode::Protected => keychain::ACCOUNT,
        GateMode::Prompt => keychain::ACCOUNT_PROMPT,
        GateMode::HelloKey => return Err(AutofillError::Locked),
    };
    // The stored key is the app key, the primary's; any other workspace opens
    // through its own key sealed under it, and one without is not offered a
    // Face ID unlock by the app either.
    if workspace != PRIMARY_ID && !dir.join(WRAPPED_KEY_FILE).exists() {
        return Err(AutofillError::Locked);
    }
    Ok(VaultLocation {
        root: root.to_string_lossy().into_owned(),
        workspace,
        keychain_service: keychain::SERVICE.to_string(),
        keychain_account: keychain_account.to_string(),
    })
}

/// Open the vault at `location` with `key`, the bytes of its keychain item.
#[uniffi::export]
pub fn open_vault(location: VaultLocation, key: Vec<u8>) -> Result<Arc<Vault>, AutofillError> {
    let dir = dir_of(&PathBuf::from(&location.root), &location.workspace);
    ready(&dir)?;
    let app_key = Zeroizing::new(key);
    let material = if location.workspace == PRIMARY_ID {
        app_key
    } else {
        let sealed =
            fs::read_to_string(dir.join(WRAPPED_KEY_FILE)).map_err(|e| match e.kind() {
                std::io::ErrorKind::NotFound => AutofillError::Locked,
                _ => AutofillError::Io {
                    message: e.to_string(),
                },
            })?;
        crypto::open_workspace_key(&app_key, &location.workspace, &sealed)
            .map_err(|_| AutofillError::WrongKey)?
    };
    // As the app reads the same bytes: an Argon2id master where there is a
    // KDF sidecar, the legacy secret where there is none.
    let key = VaultKey::from_material(material, dir.join(KDF_SIDECAR_FILE).exists());
    let store = SqliteStore::open(&dir.join(DB_FILE), key.sqlcipher_key().as_slice())?;
    Ok(Arc::new(Vault {
        workspace: location.workspace,
        store,
        cipher: key.payload_cipher(),
    }))
}

// Whether the vault at `dir` is one to open: there, and not in the middle of
// a password change. Checked before the key is asked for and again before the
// open — `SqliteStore::open` makes a database where there is none, and the
// extension must never be what creates a vault.
fn ready(dir: &Path) -> Result<(), AutofillError> {
    if !fs::metadata(dir.join(DB_FILE)).is_ok_and(|m| m.len() > 0) {
        return Err(AutofillError::NoVault);
    }
    if dir.join(DB_REKEY_BACKUP_FILE).exists() {
        return Err(AutofillError::Recovering);
    }
    Ok(())
}

/// The sites iOS is filling for, as hosts. `None` is no site to go by — iOS
/// named none — and every login is admitted; otherwise a login is admitted by
/// the rule the browser extension fills by (`host_matches`): the site itself
/// or a parent of it, never across a public suffix. The list and the fill
/// both go through here, so a record iOS still holds for a site its login has
/// since been moved off is refused the same way it would be left off the list.
struct Sites(Option<Vec<String>>);

impl Sites {
    fn named(identifiers: &[String]) -> Self {
        Self((!identifiers.is_empty()).then(|| {
            identifiers
                .iter()
                .filter_map(|id| service_host(id))
                .collect()
        }))
    }

    fn admit(&self, host: &str) -> bool {
        self.0
            .as_ref()
            .is_none_or(|sites| sites.iter().any(|site| host_matches(site, host)))
    }
}

/// An open vault. Lives as long as the extension's sheet.
#[derive(uniffi::Object)]
pub struct Vault {
    workspace: String,
    store: SqliteStore,
    cipher: PayloadCipher,
}

#[uniffi::export]
impl Vault {
    /// The logins for the sites iOS names — each identifier a domain or a
    /// URL, admitted by [`Sites`] — that have a password to fill
    /// ([`fills_password`]). The listing is read for all of them; a row is
    /// unsealed only when the listing cannot vouch for it, and then for the
    /// same two things the fill needs — the name it signs in with
    /// (`Entry::login_name`, the name the app publishes to QuickType for the
    /// same row) and whether there is a password at all. The list carries the
    /// name, and nothing else of the payload.
    pub fn credentials_for(
        &self,
        service_identifiers: Vec<String>,
    ) -> Result<Vec<Credential>, AutofillError> {
        let sites = Sites::named(&service_identifiers);
        let mut credentials = Vec::new();
        for meta in self.store.list()? {
            if meta.kind != "login" || !sites.admit(&meta.url_host) {
                continue;
            }
            let username = meta.username.as_deref().filter(|u| !u.is_empty());
            let user = match username {
                Some(user) if listing_vouches(meta.has_passkey, username) => user.to_string(),
                // A row that will not unseal is left off rather than failing
                // the list: the key opened the database, so it is that row's
                // alone — and it could not be filled either.
                _ => match self.entry(&meta.id) {
                    Ok(Some(entry)) if fills_password(meta.has_passkey, username, &entry) => {
                        listed_name(&entry)
                    }
                    _ => continue,
                },
            };
            credentials.push(Credential {
                record: format!("{}/{}", self.workspace, meta.id),
                user,
                title: meta.title,
                host: meta.url_host,
            });
        }
        Ok(credentials)
    }

    /// The name and password `record` fills, unsealing that row alone — for
    /// the sites iOS is filling for, which it names as it does for the list.
    /// The row is admitted by the rule the list is, checked here again against
    /// the vault rather than trusted from what iOS holds: a QuickType
    /// suggestion the app published before the login was moved to another
    /// site, or deleted, is `NotFound`, not the login's current password
    /// filled into its former site.
    pub fn password(
        &self,
        record: String,
        service_identifiers: Vec<String>,
    ) -> Result<Password, AutofillError> {
        let id = self.entry_of(&record)?;
        // `get` answers nothing for a row in the trash.
        let row = self.store.get(id)?.ok_or(AutofillError::NotFound)?;
        if row.kind != "login" || !Sites::named(&service_identifiers).admit(&row.url_host) {
            return Err(AutofillError::NotFound);
        }
        let entry = self.cipher.unseal(&row.id, &row.payload)?;
        if !fills_password(row.has_passkey, row.username.as_deref(), &entry) {
            return Err(AutofillError::NotFound);
        }
        // Sent as saved, spaces and all, as the browser host sends it: the
        // name is the credential, and only its label is trimmed.
        Ok(Password {
            user: entry.login_name().unwrap_or_default().to_string(),
            password: entry.password.clone().unwrap_or_default(),
        })
    }

    /// The passkeys for `rp_id` that `allowed_credential_ids` admits (none is
    /// all of them), newest first: the list the authenticator itself picks
    /// from, so what the sheet offers is what can sign.
    pub fn passkeys_for(
        &self,
        rp_id: String,
        allowed_credential_ids: Vec<Vec<u8>>,
    ) -> Result<Vec<PasskeyAccount>, AutofillError> {
        Ok(self
            .passkeys(&rp_id, &descriptors(&allowed_credential_ids))?
            .into_iter()
            .filter_map(|stored| {
                Some(PasskeyAccount {
                    credential_id: key::decode_credential_id(&stored.passkey.credential_id).ok()?,
                    record: format!("{}/{}", self.workspace, stored.entry_id),
                    user_name: stored.passkey.user_name,
                    user_display_name: stored.passkey.user_display_name,
                    created_at: stored.passkey.created_at,
                })
            })
            .collect())
    }

    /// Make a passkey for the site and keep it: on the site's one login when
    /// it has exactly one, on a new login otherwise, as on the desktop. The
    /// user said yes on the sheet before this is called.
    ///
    /// iOS only learns of the passkey for QuickType when the app next runs and
    /// publishes its identities; until then the sheet's list offers it.
    pub fn register_passkey(
        &self,
        request: PasskeyRegistration,
    ) -> Result<RegisteredPasskey, AutofillError> {
        let algorithms = &request.supported_algorithms;
        if !algorithms.is_empty() && !algorithms.contains(&ES256) {
            return Err(AutofillError::Unsupported);
        }
        let exclude = descriptors(&request.excluded_credential_ids);
        let request = make_credential::Request {
            client_data_hash: request.client_data_hash.into(),
            rp: make_credential::PublicKeyCredentialRpEntity {
                id: request.rp_id,
                name: request.rp_name,
            },
            user: PublicKeyCredentialUserEntity {
                id: request.user_handle.into(),
                name: request.user_name,
                display_name: request.user_display_name.unwrap_or_default(),
            },
            pub_key_cred_params: vec![PublicKeyCredentialParameters {
                ty: PublicKeyCredentialType::PublicKey,
                alg: coset::iana::Algorithm::ES256,
            }],
            exclude_list: (!exclude.is_empty()).then_some(exclude),
            extensions: None,
            // As the browser host asks: every passkey here is discoverable
            // anyway, and verified by the unlock.
            options: make_credential::Options {
                rk: false,
                up: true,
                uv: true,
            },
            pin_auth: None,
            pin_protocol: None,
        };
        let created = run(self.authenticator(Answered::Yes).make_credential(request))?;
        let credential_id = created
            .auth_data
            .attested_credential_data
            .as_ref()
            .map(|attested| attested.credential_id().to_vec())
            .ok_or_else(|| io("the new passkey has no credential id"))?;
        Ok(RegisteredPasskey {
            credential_id,
            attestation_object: created.as_webauthn_bytes().to_vec(),
        })
    }

    /// Sign iOS's client data hash with the passkey picked. The account is
    /// resolved here, from the same list [`Self::passkeys_for`] gives, and
    /// the core is told the pick through its consent — so the core's own
    /// narrowing to that record is what signs.
    pub fn assert_passkey(
        &self,
        request: PasskeyAssertion,
    ) -> Result<AssertedPasskey, AutofillError> {
        let allow = descriptors(&request.allowed_credential_ids);
        let found = self.passkeys(&request.rp_id, &allow)?;
        let index = match &request.record {
            Some(record) => {
                let entry = self.entry_of(record)?;
                found.iter().position(|stored| stored.entry_id == entry)
            }
            None if found.len() == 1 => Some(0),
            None if found.is_empty() => None,
            None => return Err(AutofillError::Denied),
        }
        .ok_or(AutofillError::NotFound)?;
        let picked = Answered::Account {
            index,
            credential_id: found[index].passkey.credential_id.clone(),
        };
        let request = get_assertion::Request {
            rp_id: request.rp_id,
            client_data_hash: request.client_data_hash.into(),
            allow_list: (!allow.is_empty()).then_some(allow),
            extensions: None,
            options: get_assertion::Options {
                rk: false,
                up: true,
                uv: true,
            },
            pin_auth: None,
            pin_protocol: None,
        };
        let signed = run(self.authenticator(picked).get_assertion(request))?;
        Ok(AssertedPasskey {
            credential_id: signed
                .credential
                .map(|credential| credential.id.to_vec())
                .ok_or_else(|| io("the assertion names no credential"))?,
            user_handle: signed.user.map(|user| user.id.to_vec()).unwrap_or_default(),
            authenticator_data: signed.auth_data.to_vec(),
            signature: signed.signature.to_vec(),
        })
    }
}

impl Vault {
    // The record's entry id, when the record is this workspace's.
    fn entry_of<'a>(&self, record: &'a str) -> Result<&'a str, AutofillError> {
        record
            .split_once('/')
            .filter(|(workspace, _)| *workspace == self.workspace)
            .map(|(_, id)| id)
            .ok_or(AutofillError::NotFound)
    }

    fn authenticator(&self, consent: Answered) -> Authenticator<SessionVault<'_>> {
        Authenticator::new(SessionVault::new(&self.store, &self.cipher), consent)
    }

    // The core's own list of what could sign — `Authenticator::get_assertion`
    // offers the user exactly this — so an index into it is an index into
    // what the core asks about.
    fn passkeys(
        &self,
        rp_id: &str,
        allow: &[PublicKeyCredentialDescriptor],
    ) -> Result<Vec<Stored>, AutofillError> {
        VaultCredentialStore::new(
            SessionVault::new(&self.store, &self.cipher),
            Default::default(),
        )
        .matching((!allow.is_empty()).then_some(allow), rp_id)
        .map_err(ceremony_error)
    }

    // The row `id` unsealed, or `None` when there is no such row.
    fn entry(&self, id: &str) -> Result<Option<Entry>, AutofillError> {
        let Some(row) = self.store.get(id)? else {
            return Ok(None);
        };
        Ok(Some(self.cipher.unseal(&row.id, &row.payload)?))
    }
}

/// The name a login is listed under: `Entry::login_name`, trimmed, as the
/// listing's `username` column has it (`store::migrate::derived_username`)
/// and as the app labels the QuickType identity. A label only: what is
/// filled is the name as saved.
fn listed_name(entry: &Entry) -> String {
    entry.login_name().unwrap_or_default().trim().to_string()
}

/// Whether a login's listing — its `has_passkey` and `username` columns —
/// vouches for it having a password to fill: a login with a username and no
/// passkey does, as far as the app's QuickType identities are concerned
/// (`credential_identities::needs_entry` in the app unseals exactly the rest).
/// A row with no username column, or a passkey on it — the passkey-only kind
/// an import brings has no password — the listing cannot vouch for.
fn listing_vouches(has_passkey: bool, username: Option<&str>) -> bool {
    !has_passkey && username.is_some_and(|u| !u.is_empty())
}

/// Whether a login has a password to fill: the one rule for the list and the
/// fill, so nothing is offered that will not fill and nothing refused that
/// was offered. The listing's word where it vouches ([`listing_vouches`]),
/// the payload's otherwise.
fn fills_password(has_passkey: bool, username: Option<&str>, entry: &Entry) -> bool {
    listing_vouches(has_passkey, username) || entry.has_password()
}

/// The user's answer, given on the sheet before a ceremony starts: the core
/// asks, and this repeats it. A registration's yes is the confirmation; a
/// sign-in's is the account picked, by its place in the list the core asks
/// with — and only while that place still holds the passkey picked.
enum Answered {
    Yes,
    Account { index: usize, credential_id: String },
}

impl UserConsent for Answered {
    fn approve(&self, ceremony: Ceremony<'_>) -> Option<usize> {
        match (self, ceremony) {
            (Self::Yes, Ceremony::Register { .. }) => Some(0),
            (
                Self::Account {
                    index,
                    credential_id,
                },
                Ceremony::SignIn { accounts, .. },
            ) => accounts
                .get(*index)
                .filter(|account| account.credential_id == *credential_id)
                .map(|_| *index),
            _ => None,
        }
    }
}

// The authenticator's traits are async, but nothing under them waits on
// anything: the answer is in before a ceremony starts. A current-thread
// runtime is all the driving it needs.
fn run<T>(ceremony: impl Future<Output = Result<T, StatusCode>>) -> Result<T, AutofillError> {
    tokio::runtime::Builder::new_current_thread()
        .build()
        .map_err(|e| io(e.to_string()))?
        .block_on(ceremony)
        .map_err(ceremony_error)
}

// The CTAP status a ceremony ends with, as the one thing the extension does
// about it. The vault's own failures are logged by the core and arrive as the
// catch-all.
fn ceremony_error(status: StatusCode) -> AutofillError {
    let is = |error: Ctap2Error| status == StatusCode::from(error);
    if is(Ctap2Error::NoCredentials) {
        AutofillError::NotFound
    } else if is(Ctap2Error::OperationDenied) {
        AutofillError::Denied
    } else if is(Ctap2Error::CredentialExcluded) {
        AutofillError::Excluded
    } else if is(Ctap2Error::UnsupportedAlgorithm) {
        AutofillError::Unsupported
    } else {
        io(format!("the passkey could not be used ({status:?})"))
    }
}

fn io(message: impl Into<String>) -> AutofillError {
    AutofillError::Io {
        message: message.into(),
    }
}

fn descriptors(ids: &[Vec<u8>]) -> Vec<PublicKeyCredentialDescriptor> {
    ids.iter()
        .map(|id| PublicKeyCredentialDescriptor {
            ty: PublicKeyCredentialType::PublicKey,
            id: id.clone().into(),
            transports: None,
        })
        .collect()
}

// The host a service identifier names: iOS passes a URL for a web page and a
// bare domain for an app's associated domain, and both read here the way a
// browser's page does for the browser host.
fn service_host(identifier: &str) -> Option<String> {
    let identifier = identifier.trim();
    if identifier.is_empty() {
        return None;
    }
    site_host(identifier).or_else(|| site_host(&format!("https://{identifier}")))
}

