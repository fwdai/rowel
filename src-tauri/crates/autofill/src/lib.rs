//! The vault as the iOS AutoFill extension (`app.rowel.mobile.autofill`) reads
//! it: the active workspace's database, found in the App Group container the
//! app keeps it in, opened with the key the app enrolled for Face ID, and read
//! for the logins that belong to the site being filled — or used as the
//! passkey authenticator for it (iOS 17 and later).
//!
//! Swift does the platform half — the container path, the Face ID prompt, the
//! keychain read — and hands Rust plain strings and bytes. Everything that
//! decides where the vault is, how the key opens it, which logins match and
//! how a passkey is made or signs is `rowel_core`, the code the app itself
//! runs.
//!
//! ## Passkeys
//! iOS is the WebAuthn client here: it checks the relying party against the
//! calling app or page and writes `clientDataJSON` itself, and hands the
//! extension only its hash. So unlike the browser host (`browser::passkeys` in
//! the app), nothing here builds client data or checks an origin; the hash is
//! signed as given. User verification is the Face ID unlock the sheet already
//! did, and the user's say is the sheet — the row tapped for a sign-in, the
//! confirmation for a registration — so the core's `UserConsent` is only told
//! the answer (`Answered`).
//!
//! The Swift side is generated by UniFFI (`bindgen.sh`).

